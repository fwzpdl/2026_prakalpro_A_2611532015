


angka1_2015 = int(input("Input angka ke-1 : "))
angka2_2015 = int(input("Input angka ke-2 : "))

#Lebih besar dari
hasil_2015 = angka1_2015 > angka2_2015
print("\nOperator lenih besar dari")
print("angka1_2015 > angka2_2015 = ", hasil_2015)

#Lebih kecil dari
hasil_2015 = angka1_2015 < angka2_2015
print("\nOperator lebih kecil dari")
print("angka1_2015 < angka2_2015 = ", hasil_2015)

#Lebih besar atau sama dengan 
hasil_2015 = angka1_2015 >= angka2_2015
print("\nOperator lebih kecil dari")
print("angka1_2015 >= angka2_2015 = ", hasil_2015)

#Lebih kecil atau sama dengan 
hasil_2015 = angka1_2015 <= angka2_2015
print("\nOperator lebih kecil dari")
print("angka1_2015 <= angka2_2015 = ", hasil_2015)

#Sama dengan
hasil_2015 = angka1_2015 == angka2_2015
print("\nOperator sama dengan")
print("angka1_2015 == angka2_2015 = ", hasil_2015)

#Tidak sama dengan
hasil_2015 = angka1_2015 != angka2_2015
print("\nOperator tidak sama dengan")
print("angka1_2015 != angka2_2015 = ", hasil_2015)

# Tambahan: perbandingan berantai dalam python
hasil_2015 = 0 < angka1_2015 < 100
